const DDRAGON_VERSION = '15.6.1';

// Mapeo de IDs internos a nombres de archivo de Data Dragon
const DDRAGON_ID_MAP: Record<string, string> = {
  Wukong: 'MonkeyKing',
};

// Iconos locales para campeones exclusivos de Wild Rift (en client/public/)
const CUSTOM_ICONS: Record<string, string> = {
  Norra: '/norra.png',
};

export const getChampionIconUrl = (id: string): string => {
  if (CUSTOM_ICONS[id]) return CUSTOM_ICONS[id];
  const ddragonId = DDRAGON_ID_MAP[id] || id;
  return `https://ddragon.leagueoflegends.com/cdn/${DDRAGON_VERSION}/img/champion/${ddragonId}.png`;
};

